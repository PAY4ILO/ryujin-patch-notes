// cards.json + ru.json -> ../wiki/data.js (both languages pre-rendered to HTML).
// Lines without a Russian translation stay in English, so a fresh Trello export never breaks the build;
// run `node untranslated.mjs` afterwards to see what is left to translate.
import fs from "node:fs";
import { Marked } from "marked";

const dir = new URL(".", import.meta.url);
const read = f => JSON.parse(fs.readFileSync(new URL(f, dir)));
const { lists, cards, exported } = read("cards.json");
const ru = read("ru.json");
const board = read("board.json");
// Corrections from patch notes newer than the Trello card: replace whole lines or append text.
const fixes = read("fixes.json");

const byShort = Object.fromEntries(cards.map(c => [c.short, c]));
const anyName = Object.fromEntries(board.cards.map(c => [c.shortLink, c.name]));
const att = Object.assign({}, ...cards.map(c => c.atts));
const imgDir = new URL("../wiki/img/", dir);
const localImg = id => fs.existsSync(new URL(id + ".webp", imgDir)) ? `wiki/img/${id}.webp` : null;

// Same rules as extract.mjs: which lines are translatable and how a line maps to its key.
function keyOf(line) {
  const urls = [];
  const key = line.replace(/\]\(([^)]+)\)/g, (m, u) => { urls.push(u); return `](§${urls.length})`; });
  return { key, urls };
}
const needs = t => {
  if (!t || /^-{3,}$/.test(t) || /^!\[[^\]]*\]\([^)]*\)$/.test(t)) return false;
  const bare = t.replace(/!\[[^\]]*\]\([^)]*\)/g, "").replace(/\[\[[A-Za-z0-9]{8}\]\]/g, "").replace(/\]\([^)]*\)/g, "]");
  return /[A-Za-z]{2,}/.test(bare);
};
const tr = s => ru[s] ?? s;

function translate(desc) {
  return desc.split("\n").map(line => {
    const t = line.trim();
    if (!needs(t)) return line;
    const { key, urls } = keyOf(t);
    const hit = ru[key];
    if (hit == null) return line;
    return line.slice(0, line.indexOf(t)) + hit.replace(/§(\d+)/g, (m, i) => urls[i - 1]);
  }).join("\n");
}

function prepare(md, lang) {
  return md
    .replace(/\[\[([A-Za-z0-9]{8})\]\]/g, (m, s) => {
      const c = byShort[s];
      if (c) return `[${lang === "ru" ? tr(c.name) : c.name}](#c-${s})`;
      return anyName[s] ? `**${anyName[s]}**` : "";
    })
    .replace(/\]\(https:\/\/trello\.com\/c\/([A-Za-z0-9]{8})[^)]*\)/g, (m, s) => byShort[s] ? `](#c-${s})` : m)
    .replace(/!\[[^\]]*\]\((https:\/\/trello\.com\/1\/cards\/[0-9a-f]+\/attachments\/([0-9a-f]{24})[^)]*)\)/g,
      (m, u, id) => `![](${localImg(id) || u})`);
}

const esc = s => s.replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
const marked = new Marked({ gfm: true });
marked.use({
  renderer: {
    heading(text, level) { const l = Math.min(level + 1, 6); return `<h${l}>${text}</h${l}>\n`; },
    html(html) { return esc(html); },
    image(href, title, text) { return `<img src="${esc(href)}" alt="${esc(text || "")}" loading="lazy" decoding="async">`; },
    link(href, title, text) {
      const ext = /^https?:/.test(href);
      return `<a href="${esc(href)}"${ext ? ' target="_blank" rel="noopener"' : ""}>${text}</a>`;
    }
  }
});
const render = md => marked.parse(md).trim();

function applyFixes(c) {
  let en = c.desc, ruText = translate(c.desc);
  const mine = fixes.filter(f => f.card === c.short);
  for (const f of mine) {
    for (const [find, enNew, ruNew] of f.replace || []) {
      const ruFind = ru[find] ?? find;
      if (!en.includes(find)) console.warn(`fix ${c.short}: EN line not found: ${find.slice(0, 50)}`);
      if (!ruText.includes(ruFind)) console.warn(`fix ${c.short}: RU line not found: ${ruFind.slice(0, 50)}`);
      en = en.replace(find, enNew);
      ruText = ruText.replace(ruFind, ruNew);
    }
    if (f.append) { en += "\n\n" + f.append[0]; ruText += "\n\n" + f.append[1]; }
  }
  return { en, ru: ruText, notes: mine.map(f => [f.note[0], f.note[1], f.date]) };
}

let untranslatedTitles = 0;
const out = {
  exported,
  lists: lists.map(l => ({ id: l.id, n: [l.name, tr(l.name)], cards: cards.filter(c => c.list === l.id).map(c => c.short) })),
  cards: {}
};
const listIndex = Object.fromEntries(lists.map((l, i) => [l.id, i]));
for (const c of cards) {
  if (!(c.name in ru)) untranslatedTitles++;
  const fx = applyFixes(c);
  out.cards[c.short] = {
    n: [c.name, tr(c.name)],
    l: listIndex[c.list],
    c: c.cover ? localImg(c.cover) : null,
    h: [render(prepare(fx.en, "en")), render(prepare(fx.ru, "ru"))],
    x: fx.notes.length ? fx.notes : undefined,
    u: c.updated.slice(0, 10)
  };
}
const js = "// Generated by wiki-src/build.mjs from the public Ryujin Trello board. Do not edit by hand.\nwindow.WIKI = " + JSON.stringify(out) + ";\n";
fs.writeFileSync(new URL("../wiki/data.js", dir), js);
console.log(`${cards.length} cards, ${(js.length / 1024).toFixed(0)} KB, titles kept in English: ${untranslatedTitles}`);
